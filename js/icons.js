  /* しげん id → アイコン名（data.js の RES と そろえる） */
  const RES_ICON = { danbo: 'danbo', juice: 'juice', snack: 'snack', menko: 'menko', kakera: 'kakera', genki: 'genki' };

  /* =========================================================
     SVG で かきだす
     ========================================================= */
  function partSvg(p) {
    switch (p.t) {
      case 'r': return `<rect x="${p.x}" y="${p.y}" width="${p.w}" height="${p.h}" rx="${p.r}" fill="${p.f}"/>`;
      case 'c': return `<circle cx="${p.cx}" cy="${p.cy}" r="${p.r}" fill="${p.f}"/>`;
      case 'e': return `<ellipse cx="${p.cx}" cy="${p.cy}" rx="${p.rx}" ry="${p.ry}" fill="${p.f}"/>`;
      case 'p': return p.f === 'none' ? '' : `<path d="${p.d}" fill="${p.f}"/>`;
      case 'g': return `<polygon points="${p.pts.map((q) => q.join(',')).join(' ')}" fill="${p.f}"/>`;
      case 'l': return `<line x1="${p.x1}" y1="${p.y1}" x2="${p.x2}" y2="${p.y2}" `
        + `stroke="${p.s}" stroke-width="${p.w}" stroke-linecap="round"/>`;
      default: return '';
    }
  }

  /** アイコンの SVG 文字列。size は px（きほん 1em） */
  function svg(name, size) {
    const parts = ICONS[name];
    if (!parts) return '';
    const s = size ? ` width="${size}" height="${size}"` : '';
    return `<svg class="ico" viewBox="0 0 32 32"${s} aria-hidden="true" focusable="false">`
      + parts.map(partSvg).join('') + '</svg>';
  }

  /** <span class="ico-wrap"> に いれた DOM */
  function el(name, size) {
    const span = document.createElement('span');
    span.className = 'ico-wrap';
    span.innerHTML = svg(name, size);
    return span;
  }

  /** しげんの アイコン（id から） */
  function res(id, size) { return svg(RES_ICON[id] || id, size); }

  /* =========================================================
     Canvas に かく（中心ぞろえ）
     ========================================================= */
  function roundRect(ctx, x, y, w, h, r) {
    const rr = Math.min(r, w / 2, h / 2);
    ctx.beginPath();
    ctx.moveTo(x + rr, y);
    ctx.lineTo(x + w - rr, y); ctx.quadraticCurveTo(x + w, y, x + w, y + rr);
    ctx.lineTo(x + w, y + h - rr); ctx.quadraticCurveTo(x + w, y + h, x + w - rr, y + h);
    ctx.lineTo(x + rr, y + h); ctx.quadraticCurveTo(x, y + h, x, y + h - rr);
    ctx.lineTo(x, y + rr); ctx.quadraticCurveTo(x, y, x + rr, y);
    ctx.closePath();
  }

  function paint(ctx, name, cx, cy, size) {
    const parts = ICONS[name];
    if (!parts) return;
    const k = size / 32;
    ctx.save();
    ctx.translate(cx - size / 2, cy - size / 2);
    ctx.scale(k, k);
    parts.forEach((p) => {
      ctx.fillStyle = p.f || '#000';
      switch (p.t) {
        case 'r': roundRect(ctx, p.x, p.y, p.w, p.h, p.r); ctx.fill(); break;
        case 'c': ctx.beginPath(); ctx.arc(p.cx, p.cy, p.r, 0, Math.PI * 2); ctx.fill(); break;
        case 'e': ctx.beginPath(); ctx.ellipse(p.cx, p.cy, p.rx, p.ry, 0, 0, Math.PI * 2); ctx.fill(); break;
        case 'p':
          if (p.f === 'none') break;
          try { ctx.fill(new Path2D(p.d)); } catch (e) { /* Path2D なし = えがかない */ }
          break;
        case 'g':
          ctx.beginPath();
          p.pts.forEach((q, i) => (i ? ctx.lineTo(q[0], q[1]) : ctx.moveTo(q[0], q[1])));
          ctx.closePath(); ctx.fill();
          break;
        case 'l':
          ctx.strokeStyle = p.s; ctx.lineWidth = p.w; ctx.lineCap = 'round';
          ctx.beginPath(); ctx.moveTo(p.x1, p.y1); ctx.lineTo(p.x2, p.y2); ctx.stroke();
          break;
        default: break;
      }
    });
    ctx.restore();
  }

  /** index.html に おいた data-icon を うめる */
  function fillStatic(root) {
    (root || document).querySelectorAll('[data-icon]').forEach((node) => {
      const n = node.getAttribute('data-icon');
      if (!ICONS[n] || node.firstElementChild) return;
      node.innerHTML = svg(n);
    });
  }

  GP.icons = { svg, el, res, paint, fillStatic, has: (n) => !!ICONS[n], names: () => Object.keys(ICONS) };
