/* =========================================================
   icons.js — ゲーム内アイコンの ベクター定義

   絵文字は 端末の 絵文字フォント しだいで 見た目が かわり、
   あたらしい 絵文字は ふるい 端末で でない（豆腐に なる）ため、
   アイコンは すべて じぶんで えがく。

   ・ひとつの 定義（32x32）から SVG と Canvas の りょうほうを だす
   ・SVG   … GP.icons.svg(name, size)  → 文字列（html: に そのまま つかえる）
   ・DOM   … GP.icons.el(name, size)   → <span class="ico">
   ・Canvas… GP.icons.paint(ctx, name, cx, cy, size)  ※中心ぞろえ

   かたち の かきかた（すべて 32x32 の ざひょう）:
     R(x,y,w,h,r,fill)        かどまる しかく
     C(cx,cy,r,fill)          まる
     E(cx,cy,rx,ry,fill)      だえん
     P(d,fill)                パス（Path2D で canvas にも でる）
     G([[x,y],...],fill)      ただの ずけい
     L(x1,y1,x2,y2,col,w)     せん
   ========================================================= */
